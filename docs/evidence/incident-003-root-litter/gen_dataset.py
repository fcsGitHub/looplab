"""Deterministic dataset generator for the looplab optimization task.

Produces a reproducible binary-classification dataset with a fixed seed.
The data is synthetic but generated by an explicit, auditable process so that
every number in the final report can be reproduced from scratch.

Design
------
- n_samples points in R^d, two Gaussian-ish clusters with overlap.
- A subset of features is informative; the rest are pure noise.
- A non-linear interaction term is injected so that *linear* baselines are
  limited and *heuristic* feature engineering can yield real gains.
- Split: train / validation / test (deterministic, seeded).

Output: data/dataset.npz  (X_train,y_train,X_val,y_val,X_test,y_test, meta)
"""
from __future__ import annotations

import argparse
import json
import os

import numpy as np

DEFAULT_SEED = 20240517
DEFAULT_N = 4000
DEFAULT_D = 12
INFORMATIVE = [0, 1, 2, 3]          # informative linear features
INTERACTION = (0, 1)               # non-linear interaction pair
NOISE_STD = 1.0


def make_dataset(seed: int = DEFAULT_SEED, n: int = DEFAULT_N, d: int = DEFAULT_D):
    rng = np.random.default_rng(seed)

    X = rng.normal(0.0, 1.0, size=(n, d))

    # Linear logit from informative features.
    w = np.zeros(d)
    w[INFORMATIVE] = np.array([1.6, -1.3, 0.9, 0.7])

    logit = X @ w
    # Non-linear interaction: only detectable if the model can represent it.
    i, j = INTERACTION
    logit = logit + 1.8 * (X[:, i] * X[:, j])
    # Mild quadratic term on feature 2.
    logit = logit + 0.6 * (X[:, 2] ** 2 - 1.0)

    logit = logit + rng.normal(0.0, NOISE_STD, size=n)
    p = 1.0 / (1.0 + np.exp(-logit))
    y = (rng.random(n) < p).astype(np.int64)

    # Deterministic split.
    idx = rng.permutation(n)
    n_train = int(0.6 * n)
    n_val = int(0.2 * n)
    tr, va, te = idx[:n_train], idx[n_train:n_train + n_val], idx[n_train + n_val:]

    meta = {
        "seed": seed,
        "n": n,
        "d": d,
        "informative": INFORMATIVE,
        "interaction": list(INTERACTION),
        "noise_std": NOISE_STD,
        "n_train": int(len(tr)),
        "n_val": int(len(va)),
        "n_test": int(len(te)),
        "pos_rate": float(y.mean()),
    }
    return {
        "X_train": X[tr], "y_train": y[tr],
        "X_val": X[va], "y_val": y[va],
        "X_test": X[te], "y_test": y[te],
        "meta": meta,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=DEFAULT_SEED)
    ap.add_argument("--n", type=int, default=DEFAULT_N)
    ap.add_argument("--d", type=int, default=DEFAULT_D)
    ap.add_argument("--out", default=os.path.join("data", "dataset.npz"))
    args = ap.parse_args()

    ds = make_dataset(args.seed, args.n, args.d)
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    np.savez_compressed(args.out, **ds)
    print(json.dumps(ds["meta"], indent=2))
    print("wrote", args.out)


if __name__ == "__main__":
    main()
